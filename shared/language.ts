export function translate(text: string, language: Language): string {
  return language === 'hi' ? translations[text] ?? text : text
}

export function readSavedLanguage(): Language {
  try {
    return window.localStorage.getItem('nexusflow-language') === 'hi' ? 'hi' : 'en'
  } catch {
    return 'en'
  }
}

export function saveLanguage(language: Language): void {
  window.localStorage.setItem('nexusflow-language', language)
}
